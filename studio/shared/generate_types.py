"""Generate browser contracts from canonical JSON Schema; no geometry ontology."""
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]


def ts(schema):
    if '$ref' in schema:
        location,_,fragment=schema['$ref'].partition('#')
        value=json.loads((ROOT/'schemas'/location.rsplit('/',1)[-1]).read_text())
        for key in fragment.strip('/').split('/') if fragment else []:value=value[key]
        return ts(value)
    if 'const' in schema:return json.dumps(schema['const'])
    if 'enum' in schema:return ' | '.join(json.dumps(v) for v in schema['enum'])
    for key,operator in [('oneOf',' | '),('anyOf',' | '),('allOf',' & ')]:
        if key in schema:return '('+operator.join(ts(v) for v in schema[key])+')'
    kind=schema.get('type')
    if isinstance(kind,list):return ' | '.join(ts({**schema,'type':k}) for k in kind)
    if kind=='array':return '('+ts(schema.get('items',{}))+')[]'
    if kind=='object' or 'properties' in schema:
        fields=[json.dumps(k)+('' if k in schema.get('required',[]) else '?')+': '+ts(v) for k,v in schema.get('properties',{}).items()]
        if not fields:return 'Record<string, unknown>'
        return '{ '+ '; '.join(fields)+' }'
    return {'number':'number','integer':'number','string':'string','null':'null','boolean':'boolean'}.get(kind,'unknown')


def main():
    author=json.loads((ROOT/'schemas/authoring.schema.json').read_text())
    command=json.loads((ROOT/'schemas/authoring_command.schema.json').read_text())
    text='// Generated by studio/shared/generate_types.py. Do not edit.\n'
    for name,schema in [('Observation',author['$defs']['observation']),('AuthoringCommand',command),('Measurement',author['$defs']['measurement'])]:
        text+='export type '+name+' = '+ts(schema)+';\n'
    dest=Path(__file__).parent/'generated/contracts.ts';dest.parent.mkdir(exist_ok=True)
    dest.write_text(text,encoding='utf-8',newline='\n')


if __name__=='__main__':main()
